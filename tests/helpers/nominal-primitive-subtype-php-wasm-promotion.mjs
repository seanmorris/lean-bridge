/**
 * Derive four inventory references from validated evidence or its digest precheck.
 *
 * @param checked - Validated archive descriptor.
 * @param read - Reader of repository-relative immutable evidence bytes.
 */
const referencesFromEvidence = async (checked, read) => {
	const index = JSON.parse(await read(`${nominalPrimitiveSubtypePhpWasmEvidence}/index.json`));
	assert.equal(index.producerCommit, checked.producerCommit);
	assert.equal(index.runs.length, checked.selections.length);
	const references = [];
	for(const [position, selection] of checked.selections.entries())
	{
		const run = index.runs[position], label = `${run.route}-${run.mode}`;
		assert.equal(selection.route, run.route); assert.equal(selection.mode, run.mode);
		const report = JSON.parse(await read(`${nominalPrimitiveSubtypePhpWasmEvidence}/${label}/records/report.json`));
		const files = checked.files.filter(file => file.path.startsWith(label + "/")
			|| file.path.startsWith("sources/") || file.path.startsWith("checkers/"));
		const counts = { ...run, ...run.controls };
		delete counts.controls; delete counts.label;
		counts.runtime = {
			node: report.phpWasm.nodeVersion
			, chromium: report.phpWasm.browserVersion
			, php: report.phpWasm.runtime.pins.phpVersion
			, phpWasm: report.phpWasm.host.version
			, npm: report.phpWasm.npm.version
			, composer: report.phpWasm.composer.composerVersion
		};
		references.push({
			id: `nominal-primitive-subtype-php-wasm-${run.route}-${run.mode}-installed`
			, route: run.route, mode: run.mode
			, sourcePath: run.route === "ordinary" ? "ordinary-source" : "reviewed-ir"
			, profiles: [...nominalPrimitiveSubtypePhpWasmProfiles]
			, revision: checked.producerCommit, counts, command: commandFor(run)
			, scope: `Two independent author builds reproduce the complete Composer API, npm component and npm shared-runtime archives. Author and build roots are removed before offline installation; unchanged weak and strict callers replay in twelve Node and Chromium contexts after moving the installed tree. ${run.mode === "full" ? "The full API checks all nineteen primitive fields, per-site constructors and normalization, repeated fields, active variants, aliases, nested copied containers, mixed Fin guards, exact rejection paths, caller snapshots and recovery." : "The standalone result-only API projects all nineteen primitive payloads through scalars, copied containers, records, variants and aliases without any input constructor selections."} ${nominalPrimitiveSubtypePhpWasmLimit}`
			, files: [{
				path: nominalPrimitiveSubtypePhpWasmEvidence + "/index.json"
				, sha256: nominalPrimitiveSubtypePhpWasmEvidenceSha256
			}
			, ...files.map(file => ({
				path: nominalPrimitiveSubtypePhpWasmEvidence + "/" + file.path
				, sha256: file.sha256
			}))]
			, artifacts: report.receipt.packages.flatMap(pkg => pkg.artifacts)
				.map(({ path, sha256: digest }) => ({ path, sha256: digest }))
		});
	}
	return references;
};

let defaultReferences;

/**
 * Stream-check the immutable archive without expanding its Composer packages.
 * The evidence gate separately validates ZIP contents and mutation controls.
 *
 * @param read - Reader of immutable repository-relative evidence bytes.
 * @param verifyFiles - Whether to hash every retained file.
 */
const checkPromotionEvidence = async (read, verifyFiles) => {
	const indexPath = nominalPrimitiveSubtypePhpWasmEvidence + "/index.json";
	const bytes = Buffer.from(await read(indexPath));
	assert.equal(sha256(bytes), nominalPrimitiveSubtypePhpWasmEvidenceSha256);
	const index = JSON.parse(bytes); assert.equal(bytes.toString(), canonicalJson(index));
	assert.equal(index.schemaVersion, 1);
	assert.equal(index.kind, "nominal-primitive-subtype-php-wasm-installed-v1");
	assert.equal(index.producerCommit, nominalPrimitiveSubtypePhpWasmProducer);
	assert.equal(index.loadCeiling, nominalPrimitiveSubtypePhpWasmLoadCeiling);
	assert.deepEqual(index.runs.map(run => [run.route, run.mode]),
		nominalPrimitiveSubtypePhpWasmSelections);
	if(verifyFiles) for(const file of index.files)
	{
		const value = Buffer.from(await read(
			nominalPrimitiveSubtypePhpWasmEvidence + "/" + file.path
		));
		assert.equal(value.length, file.bytes, file.path);
		assert.equal(sha256(value), file.sha256, file.path);
	}
	return {
		producerCommit: index.producerCommit
		, files: index.files
		, selections: index.runs.map(run => ({ route: run.route, mode: run.mode }))
	};
};

/**
 * Authenticate every retained byte before deriving promotion references.
 * ZIP expansion and negative-control replay stay in the evidence gate instead
 * of being repeated while rewriting the inventory.
 *
 * @param read - Reader of immutable repository-relative evidence bytes.
 */
export const nominalPrimitiveSubtypePhpWasmReferences = async (read = readFile) => {
	if(read !== readFile)
		return referencesFromEvidence(await checkPromotionEvidence(read, true), read);
	defaultReferences ??= referencesFromEvidence(
		await checkPromotionEvidence(readFile, true), readFile
	);
	return structuredClone(await defaultReferences);
};

// Reject changed reference metadata before streaming the complete archive.
// Every accepted promotion still checks every retained byte above.
const referencePrecheck = async () => {
	const bytes = Buffer.from(await readFile(nominalPrimitiveSubtypePhpWasmEvidence + "/index.json"));
	const index = JSON.parse(bytes);
	const read = async path => {
		if(path === nominalPrimitiveSubtypePhpWasmEvidence + "/index.json") return bytes;
		const entry = index.files.find(file =>
			nominalPrimitiveSubtypePhpWasmEvidence + "/" + file.path === path);
		assert.ok(entry, path); const value = await readFile(path);
		assert.equal(value.length, entry.bytes); assert.equal(sha256(value), entry.sha256);
		return value;
	};
	return referencesFromEvidence(await checkPromotionEvidence(read, false), read);
};

/**
 * Supplement six proven PHP-Wasm cells and leave every other profile unchanged.
 *
 * @param original - Exact inventory before this milestone.
 * @param references - Four independently authenticated installed selections.
 */
export const promoteNominalPrimitiveSubtypePhpWasm = async (original, references) => {
	assert.deepEqual(references, await referencePrecheck());
	assert.deepEqual(references, await nominalPrimitiveSubtypePhpWasmReferences());
	const inventory = structuredClone(original), validators = [];
	for(const path of [
		"tests/helpers/nominal-primitive-subtype-php-wasm-report.mjs"
		, "tests/helpers/nominal-primitive-subtype-php-wasm-evidence.mjs"
		, "tests/helpers/nominal-primitive-subtype-php-wasm-controls.mjs"
		, "tests/helpers/nominal-primitive-subtype-php-wasm-provenance.mjs"
		, "tests/helpers/nominal-primitive-subtype-php-wasm-promotion.mjs"
		, "tests/helpers/nominal-primitive-subtype-php-wasm-promotion-tests.mjs"
		, "tests/helpers/nominal-primitive-subtype-php-wasm-ci-report.mjs"
		, "tests/helpers/nominal-primitive-subtype-php-wasm-ci-workflow.mjs"
		, "scripts/check-nominal-primitive-subtype-php-wasm-ci.mjs"
		, "scripts/run-nominal-primitive-subtype-php-wasm-ci.sh"
		, ".github/workflows/nominal-primitive-subtype-php-wasm.yml"
	]) validators.push({ path, sha256: sha256(await readFile(path)) });
	for(const reference of references)
	{
		assert.ok(!inventory.evidence.some(item => item.id === reference.id),
			"Already promoted: " + reference.id);
		inventory.evidence.push({
			id: reference.id, kind: "installed", revision: reference.revision
			, command: reference.command, scope: reference.scope
			, files: [...validators, ...reference.files]
			, artifacts: reference.artifacts.map(item => ({
				...item, path: reference.id + "/" + item.path
			}))
		});
	}
	for(const path of ["ordinary-source", "reviewed-ir"])
	{
		const matches = inventory.observations.filter(item => item.path === path
			&& item.shapes.includes("subtype")
			&& item.profiles.some(profile => nominalPrimitiveSubtypePhpWasmProfiles.includes(profile)));
		const mainId = path === "ordinary-source"
			? "php-wasm-subtype-ordinary" : "php-wasm-subtype-reviewed";
		assert.deepEqual(matches.map(item => [item.id, item.profiles, item.shapes, item.positions]), [
			[mainId, nominalPrimitiveSubtypePhpWasmProfiles, ["subtype"], ["parameter", "result"]]
			, [`nominal-subtype-php-wasm-fields-${path}`
				, nominalPrimitiveSubtypePhpWasmProfiles, ["subtype"], ["field"]]
		], "Missing or overlapping PHP-Wasm Subtype observations");
		const matched = references.filter(item => item.sourcePath === path);
		const ids = matched.map(item => item.id); assert.equal(matched.length, 2);
		const scope = matched.map(item => item.scope).join(" ");
		for(const observation of matches)
		{
			observation.scope = observation.scope.replaceAll(nominalSubtypePhpWasmLimit, "").trimEnd()
				+ " Additional primitive-base nominal PHP-Wasm acceptance: " + scope;
			assert.equal(observation.conversionNotes.subtype.split(nominalSubtypePhpWasmConversion).length, 2);
			observation.conversionNotes.subtype = observation.conversionNotes.subtype.replace(
				nominalSubtypePhpWasmConversion, nominalPrimitiveSubtypePhpWasmConversion
			);
			assert.equal(observation.limitations.filter(item => item === nominalSubtypePhpWasmLimit).length, 1);
			observation.limitations = observation.limitations.map(item =>
				item === nominalSubtypePhpWasmLimit ? nominalPrimitiveSubtypePhpWasmLimit : item);
			for(const position of observation.positions)
				observation.hostTypes.subtype[position] = {
					parameter: nominalPrimitiveSubtypePhpWasmParameter
					, result: nominalPrimitiveSubtypePhpWasmResult
					, field: nominalPrimitiveSubtypePhpWasmField
				}[position];
			for(const stage of Object.values(observation.stages))
			{
				assert.equal(stage.state, "passed"); stage.evidence.push(...ids);
				stage.note = stage.note.replaceAll(nominalSubtypePhpWasmLimit, "").trimEnd()
					+ " Additional primitive-base nominal PHP-Wasm acceptance: " + scope;
			}
		}
	}
	return inventory;
};
