/**
 * Bind recursive Cargo locks to the established closed dependency grammar.
 *
 * @file
 */
import assert from "node:assert/strict";
import { sha256 } from "../../src/capsule/node.mjs";
import {
	checkNestedCheckedRecordRustDependencyRecords
	, nestedCheckedRecordRustDependencyManifests
	, nestedCheckedRecordRustLockedPackages
} from "./nested-checked-record-rust-dependency-records.mjs";
import { recursiveCheckedRecordRustPackage } from "./recursive-checked-record-rust-fixture.mjs";

const nestedPackage = "nestedcheckedrecords";
const recursiveConsumer = "recursive-consumer";
const header = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n";

const normalizedLock = (source, fixture) => {
	const { name } = recursiveCheckedRecordRustPackage(fixture);
	assert.notEqual(name, nestedPackage);
	const marker = `name = "${name}"\nversion = "1.0.0"`;
	assert.equal(source.split(marker).length, 2);
	return source.replace(marker, `name = "${nestedPackage}"\nversion = "1.0.0"`);
};

/**
 * Decode the frozen lock while preserving the selected public package identity.
 *
 * @param source - Original graph crate lock.
 * @param fixture - Recursive or mutually recursive graph.
 */
export const recursiveCheckedRecordRustLockedPackages = (source, fixture) => {
	const { name } = recursiveCheckedRecordRustPackage(fixture);
	return nestedCheckedRecordRustLockedPackages(normalizedLock(source, fixture))
		.map(pkg => pkg.name === nestedPackage ? {
			...pkg
			, name
			, block: pkg.block.replace(`name = "${nestedPackage}"`
				, `name = "${name}"`)
		} : pkg);
};

/**
 * Derive Cargo's exact consumer lock from the authenticated crate lock.
 *
 * @param source - Original graph crate lock.
 * @param fixture - Recursive or mutually recursive graph.
 */
export const recursiveCheckedRecordRustConsumerLock = (source, fixture) => {
	const { name } = recursiveCheckedRecordRustPackage(fixture);
	const packages = recursiveCheckedRecordRustLockedPackages(source, fixture);
	packages.push({
		name: recursiveConsumer
		, block: `name = "${recursiveConsumer}"\nversion = "0.0.0"\ndependencies = [\n "${name}",\n]\n`
	});
	return header + packages.sort((a, b) => a.name.localeCompare(b.name))
		.map(pkg => "[[package]]\n" + pkg.block).join("\n");
};

/**
 * Verify every vendored checksum record against the selected lock.
 *
 * @param options - Original dependency records and readers.
 * @param options.dependencies - Producer dependency handoff.
 * @param options.lock - Authenticated original graph crate lock.
 * @param options.read - Original retained record reader.
 * @param options.fixture - Recursive or mutually recursive graph.
 */
export const checkRecursiveCheckedRecordRustDependencyRecords = async ({
	dependencies, lock, read, fixture
}) => {
	assert.equal(dependencies.lockSha256, sha256(lock));
	const normalized = normalizedLock(lock, fixture);
	return checkNestedCheckedRecordRustDependencyRecords({
		dependencies: { ...dependencies, lockSha256: sha256(normalized) }
		, lock: normalized, read
	});
};

export const recursiveCheckedRecordRustDependencyManifests
	= nestedCheckedRecordRustDependencyManifests;
