/** @file A normal async guest awaits two canonical futures, with no delivery or pump import. */
import {renderCanonicalFutureProducer} from "../../src/backends/wit/canonical-future.mjs";

/**
 * Assemble the application, producer, and embedding entry around the actual archive's declaration.
 *
 * @param ir - Verified installed Latches Binding IR.
 */
export const scheduledApplication=ir=>{
	const d=ir.declarations.find(x=>x.source.declaration==="Latches.parked");
	const producer=renderCanonicalFutureProducer(d,4).replace("(component","(component $producer");
	return `(component
  (import "begin" (func $begin (param "arg0" u32) (param "arg1" s64) (result u32)))
  (import "release" (func $release (param "slot" u32)))
  ${producer}
  (instance $p (instantiate $producer (with "begin" (func $begin))))
  (component $app
    (type $f (future s64))
    (import "parked" (func $open (param "arg0" u32) (param "arg1" s64) (result $f)))
    (import "release" (func $release (param "slot" u32)))
    (core func $open (canon lower (func $open)))
    (core func $release (canon lower (func $release)))
    (core module $mem (memory (export "m") 1))
    (core instance $mem (instantiate $mem))
    (core func $read (canon future.read $f async (memory $mem "m")))
    (core func $drop (canon future.drop-readable $f))
    (core func $new (canon waitable-set.new))
    (core func $join (canon waitable.join))
    (core func $del (canon waitable-set.drop))
    (core func $ret (canon task.return (result s64)))
    (core module $m
      (import "" "m" (memory 1))
      (import "" "open" (func $open (param i32 i64) (result i32)))
      (import "" "release" (func $release (param i32)))
      (import "" "read" (func $read (param i32 i32) (result i32)))
      (import "" "drop" (func $drop (param i32)))
      (import "" "new" (func $new (result i32))) (import "" "join" (func $join (param i32 i32)))
      (import "" "del" (func $del (param i32))) (import "" "ret" (func $ret (param i64)))
      (global $s (mut i32) (i32.const 0)) (global $slow (mut i32) (i32.const 0))
      (global $fast (mut i32) (i32.const 0)) (global $phase (mut i32) (i32.const 0))
      ;; Probe normal consumer behavior when the write precedes the read. The
      ;; addresses below are private to this guest, not the writer's slot table.
      (func $cell (param $slot i32) (result i32)
        (if (i32.ge_u (i32.sub (local.get $slot) (i32.const 1)) (i32.const 4)) (then unreachable))
        (i32.add (i32.const 128) (i32.shl (local.get $slot) (i32.const 2))))
      (func $park (export "park") (param $slot i32) (param $value i64)
        (i32.store (call $cell (local.get $slot)) (call $open (local.get $slot) (local.get $value))))
      (func (export "hold") (param $slot i32) (param $value i64)
        (call $park (local.get $slot) (local.get $value))
        (call $release (local.get $slot)))
      (func (export "discard") (param $slot i32)
        (call $drop (i32.load (call $cell (local.get $slot)))))
      (func (export "consume") (param $slot i32) (result i64) (local $reader i32)
        (local.set $reader (i32.load (call $cell (local.get $slot))))
        (if (i32.ne (call $read (local.get $reader) (i32.const 64)) (i32.const 0)) (then unreachable))
        (call $drop (local.get $reader)) (i64.load (i32.const 64)))
      (func $wait (result i32) (i32.or (i32.const 2) (i32.shl (global.get $s) (i32.const 4))))
      (func (export "run") (result i32)
        (global.set $s (call $new))
        (global.set $slow (call $open (i32.const 1) (i64.const -800000000000000001)))
        (global.set $fast (call $open (i32.const 2) (i64.const 900000000000000003)))
        (if (i32.ne (call $read (global.get $slow) (i32.const 8)) (i32.const -1)) (then unreachable))
        (if (i32.ne (call $read (global.get $fast) (i32.const 16)) (i32.const -1)) (then unreachable))
        (call $join (global.get $slow) (global.get $s)) (call $join (global.get $fast) (global.get $s))
        (global.set $phase (i32.const 1)) (call $release (i32.const 2)) (call $wait))
      (func (export "cb") (param $event i32) (param $id i32) (param $code i32) (result i32)
        (if (i32.or (i32.ne (local.get $event) (i32.const 4)) (local.get $code)) (then unreachable))
        (if (i32.eq (global.get $phase) (i32.const 1))
          (then
            (if (i32.ne (local.get $id) (global.get $fast)) (then unreachable))
            (if (i64.ne (i64.load (i32.const 16)) (i64.const 900000000000000003)) (then unreachable))
            (call $drop (global.get $fast)) (global.set $phase (i32.const 2))
            (call $release (i32.const 1)) (return (call $wait))))
        (if (i32.ne (local.get $id) (global.get $slow)) (then unreachable))
        (call $drop (global.get $slow)) (call $del (global.get $s))
        (call $ret (i64.add (i64.load (i32.const 8)) (i64.load (i32.const 16))))
        (i32.const 0)))
    (core instance $i (instantiate $m (with "" (instance
      (export "m" (memory $mem "m")) (export "open" (func $open)) (export "release" (func $release))
      (export "read" (func $read)) (export "drop" (func $drop)) (export "new" (func $new))
      (export "join" (func $join)) (export "del" (func $del)) (export "ret" (func $ret))))))
    (func (export "park") (param "slot" u32) (param "value" s64) (canon lift (core func $i "park")))
    (func (export "hold") (param "slot" u32) (param "value" s64) (canon lift (core func $i "hold")))
    (func (export "discard") (param "slot" u32) (canon lift (core func $i "discard")))
    (func (export "consume") (param "slot" u32) (result s64) (canon lift (core func $i "consume")))
    (func (export "run") async (result s64) (canon lift (core func $i "run") async (callback (func $i "cb")))))
  (instance $app (instantiate $app (with "parked" (func $p "start")) (with "release" (func $release))))
  (component $supervisor
    (import "app" (func $run async (result s64)))
    (core module $mem (memory (export "m") 1))
    (core instance $mem (instantiate $mem))
    (core func $run (canon lower (func $run) async (memory $mem "m")))
    (core func $new (canon waitable-set.new)) (core func $del (canon waitable-set.drop))
    (core func $drop (canon subtask.drop)) (core func $join (canon waitable.join))
    (core func $ret (canon task.return))
    (core module $m
      (import "" "m" (memory 1)) (import "" "run" (func $run (param i32) (result i32)))
      (import "" "new" (func $new (result i32))) (import "" "del" (func $del (param i32)))
      (import "" "join" (func $join (param i32 i32))) (import "" "drop" (func $drop (param i32)))
      (import "" "return" (func $return))
      (global $s (mut i32) (i32.const 0)) (global $done (mut i32) (i32.const 0))
      (func (export "launch") (result i32) (local $op i32)
        (local.set $op (call $run (i32.const 8)))
        (call $return)
        (if (i32.eq (i32.and (local.get $op) (i32.const 15)) (i32.const 2))
          (then (global.set $done (i32.const 1)) (return (i32.const 0))))
        (global.set $s (call $new))
        (call $join (i32.shr_u (local.get $op) (i32.const 4)) (global.get $s))
        (i32.or (i32.const 2) (i32.shl (global.get $s) (i32.const 4))))
      (func (export "cb") (param $ev i32) (param $id i32) (param $status i32) (result i32)
        (if (i32.ne (local.get $ev) (i32.const 1)) (then unreachable))
        (if (i32.ne (local.get $status) (i32.const 2))
          (then (return (i32.or (i32.const 2) (i32.shl (global.get $s) (i32.const 4))))))
        (call $drop (local.get $id)) (call $del (global.get $s)) (global.set $done (i32.const 1)) (i32.const 0))
      (func (export "done") (result i32) (global.get $done))
      (func (export "take") (result i64) (if (i32.eqz (global.get $done)) (then unreachable)) (i64.load (i32.const 8)))
      (func (export "tick") (result i32) (i32.const 1))
      (func (export "tick-cb") (param i32 i32 i32) (result i32) (call $return) (i32.const 0)))
    (core instance $i (instantiate $m (with "" (instance (export "m" (memory $mem "m")) (export "run" (func $run))
      (export "new" (func $new)) (export "del" (func $del)) (export "join" (func $join))
      (export "drop" (func $drop)) (export "return" (func $ret))))))
    (func (export "launch") async (canon lift (core func $i "launch") async (callback (func $i "cb"))))
    (func (export "tick") async (canon lift (core func $i "tick") async (callback (func $i "tick-cb"))))
    (func (export "done") (result bool) (canon lift (core func $i "done")))
    (func (export "take") (result s64) (canon lift (core func $i "take"))))
  (instance $s (instantiate $supervisor (with "app" (func $app "run"))))
  (export "launch" (func $s "launch")) (export "tick" (func $s "tick"))
  (export "done" (func $s "done")) (export "take" (func $s "take"))
  (export "park" (func $app "park")) (export "hold" (func $app "hold")) (export "discard" (func $app "discard")) (export "consume" (func $app "consume"))
  (export "deliver" (func $p "deliver")) (export "reap" (func $p "reap")))`;
};
