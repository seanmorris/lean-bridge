/**
 * Preserve the scalar Fin source-entry probe evidence (#1430): the six-ABI run, both feasibility attempts
 * and their runners, the exact instrumented inputs and selected producer sources at 3f2de27.
 *
 * @file
 */
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { sha256 } from "../src/capsule/node.mjs";
import { scalarFinRejectionInputs } from "../tests/helpers/scalar-fin-rejection-packages.mjs";
import { scalarFinSourceEntryProbe } from "../tests/helpers/scalar-fin-source-entry.mjs";
import { assertSourceEntryArchive, sourceEntryAbis, sourceEntryArchiveDirectory, sourceEntryInput, sourceEntryOriginals, sourceEntryReceipt, sourceEntryRevision, sourceEntrySnapshot, sourceEntrySourcePaths, writeSourceEntryArtifact } from "../tests/helpers/scalar-fin-source-entry-evidence.mjs";

const options = process.argv.slice(2);
assert.ok(options.every(option => option === "--check" || option.startsWith("--from=")), "Only --check and --from=<producing checkout> are accepted");
const from = options.find(option => option.startsWith("--from="))?.slice("--from=".length) ?? ".";
const pending = new Map(), artifacts = [];
const add = (path, bytes, originalPath) => {
	pending.set(path, bytes);
	artifacts.push({ path, originalPath, sha256: sha256(bytes), bytes: bytes.length });
};
for(const [name, file] of Object.entries(sourceEntryOriginals))
{
	const bytes = await readFile(join(from, file.original));
	assert.equal(sha256(bytes), file.sha256, file.original);
	add(`${sourceEntryArchiveDirectory}/${name}`, bytes, file.original);
}
const sources = sourceEntrySourcePaths.map(path => {
	const bytes = execFileSync("git", ["show", `${sourceEntryRevision}:${path}`], { maxBuffer: 16 * 1024 * 1024 });
	add(sourceEntrySnapshot(path), bytes, `git:${sourceEntryRevision}:${path}`);
	return { path, sha256: sha256(bytes), snapshot: sourceEntrySnapshot(path) };
});
// The inputs are regenerated by the producer helpers, which must still hold their 3f2de27 bytes here.
for(const path of ["tests/helpers/scalar-fin-source-entry.mjs", "tests/helpers/scalar-fin-rejection-packages.mjs"])
	assert.equal(sha256(await readFile(path)), sources.find(item => item.path === path).sha256, path);
const probe = scalarFinSourceEntryProbe(null);
for(const abi of sourceEntryAbis)
{
	const inputs = scalarFinRejectionInputs(abi, probe), generated = `generated at 3f2de27: scalarFinRejectionInputs(${JSON.stringify(abi)}, scalarFinSourceEntryProbe(null))`;
	add(sourceEntryInput(abi, "lean"), Buffer.from(inputs.lean), `${generated}.lean`);
	add(sourceEntryInput(abi, "consumer"), Buffer.from(inputs.consumer), `${generated}.consumer`);
}
const receipt = sourceEntryReceipt(artifacts, sources);
await assertSourceEntryArchive(receipt, async path => pending.get(path));
const bytes = Buffer.from(JSON.stringify(receipt, null, 2) + "\n");
if(!options.includes("--check"))
{
	for(const [path, content] of pending) await writeSourceEntryArtifact(path, content);
	await writeSourceEntryArtifact(`${sourceEntryArchiveDirectory}/receipt.json`, bytes);
}
process.stdout.write(`${options.includes("--check") ? "Validated" : "Archived"} ${artifacts.length} files: the six-ABI run, two feasibility attempts, six instrumented inputs and ${sources.length} sources. Receipt SHA-256 ${sha256(bytes)}\n`);
