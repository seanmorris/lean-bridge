/**
 * Reconcile locked Rust dependencies with original vendored checksum manifests.
 * Archive members are decoded in memory; historical paths are never opened.
 *
 * @file
 */
import assert from "node:assert/strict";
import { canonicalJson, sha256 } from "../../src/capsule/node.mjs";
import { readOwnedPerlCallbackVariantTar } from "./owned-perl-callback-result-variant-archives.mjs";

const registry = "registry+https://github.com/rust-lang/crates.io-index";
const header = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n";

/**
 * Decode the closed, frozen Cargo lock grammar, not arbitrary TOML input.
 *
 * @param source - Original generator-pinned Cargo.lock source.
 */
export const nestedCheckedRecordRustLockedPackages = source => {
	assert.ok(source.startsWith(header));
	const blocks = source.slice(header.length).split("[[package]]\n"); assert.equal(blocks.shift(), "");
	const packages = blocks.map(block => {
		const match = block.match(/^name = "([a-z0-9_-]+)"\nversion = "([0-9]+\.[0-9]+\.[0-9]+)"\n(?:source = "(registry\+https:\/\/github\.com\/rust-lang\/crates\.io-index)"\nchecksum = "([a-f0-9]{64})"\n)?(?:dependencies = \[\n((?: "[a-z0-9_-]+",\n)+)\]\n)?\n?$/u);
		assert.ok(match, "Unexpected pinned Cargo lock grammar");
		return { name: match[1], version: match[2], source: match[3] ?? null
			, checksum: match[4] ?? null
			, dependencies: [...(match[5] ?? "").matchAll(/"([a-z0-9_-]+)"/gu)].map(item => item[1])
			, block: block.trimEnd() + "\n" };
	});
	assert.equal(new Set(packages.map(pkg => pkg.name)).size, packages.length);
	assert.equal(packages.length, 15);
	assert.deepEqual(packages.filter(pkg => pkg.source === null).map(pkg => [pkg.name, pkg.version, pkg.dependencies]), [["nestedcheckedrecords", "1.0.0", ["num-bigint", "sha2"]]]);
	return packages;
};

/**
 * Derive the consumer lock from the frozen crate lock, including Cargo's sorting.
 *
 * @param source - Original generator-pinned Cargo.lock source.
 */
export const nestedCheckedRecordRustConsumerLock = source => {
	const packages = nestedCheckedRecordRustLockedPackages(source);
	packages.push({ name: "nested-consumer", block: 'name = "nested-consumer"\nversion = "0.0.0"\ndependencies = [\n "nestedcheckedrecords",\n]\n' });
	return header + packages.sort((a, b) => a.name.localeCompare(b.name)).map(pkg => "[[package]]\n" + pkg.block).join("\n");
};

/**
 * Require the exact pinned registry packages and archive-derived file inventories.
 *
 * @param options - Independent lock and original record readers.
 * @param options.dependencies - Original producer handoff record.
 * @param options.lock - Authenticated frozen crate lock text.
 * @param options.read - Reader for retained original checksum manifests.
 */
export const checkNestedCheckedRecordRustDependencyRecords = async ({ dependencies, lock, read }) => {
	assert.deepEqual(Object.keys(dependencies).sort(), ["archive", "lockSha256", "packages", "sha256"]);
	assert.equal(dependencies.archive, "rust-dependencies.tar.gz");
	assert.match(dependencies.sha256, /^[a-f0-9]{64}$/u); assert.equal(dependencies.lockSha256, sha256(lock));
	const packages = nestedCheckedRecordRustLockedPackages(lock).filter(pkg => pkg.source === registry).sort((a, b) => a.name.localeCompare(b.name));
	assert.deepEqual(dependencies.packages.map(pkg => pkg.directory), packages.map(pkg => `${pkg.name}-${pkg.version}`));
	const closure = [];
	for(const [index, pkg] of dependencies.packages.entries())
	{
		assert.deepEqual(Object.keys(pkg).sort(), ["checksum", "directory", "files", "manifestSha256"]);
		assert.equal(pkg.checksum, packages[index].checksum);
		const bytes = await read(`dependency-manifests/${pkg.directory}.json`), manifest = JSON.parse(bytes);
		assert.equal(sha256(bytes), pkg.manifestSha256); assert.deepEqual(Object.keys(manifest).sort(), ["files", "package"]);
		assert.equal(manifest.package, pkg.checksum); assert.equal(Object.keys(manifest.files).length, pkg.files);
		assert.ok(Number.isSafeInteger(pkg.files) && pkg.files > 0);
		for(const [path, hash] of Object.entries(manifest.files))
		{
			assert.ok(/^[A-Za-z0-9_.+/-]+$/u.test(path) && path.split("/").every(part => part && part !== "." && part !== ".."));
			assert.notEqual(path, ".cargo-checksum.json"); assert.match(hash, /^[a-f0-9]{64}$/u);
		}
		assert.ok(Object.hasOwn(manifest.files, "Cargo.toml"));
		closure.push({ directory: pkg.directory, manifestSha256: sha256(bytes)
			, fileSetSha256: sha256(canonicalJson([...Object.keys(manifest.files), ".cargo-checksum.json"].sort())) });
	}
	return closure;
};

/**
 * Retain original manifest bytes after checking every file in the dependency tar.
 * The returned records supplement the producer records without rewriting them.
 *
 * @param bytes - Original dependency archive bytes from the saved handoff.
 * @param dependencies - Original producer's archive and package identities.
 */
export const nestedCheckedRecordRustDependencyManifests = (bytes, dependencies) => {
	assert.equal(sha256(bytes), dependencies.sha256);
	const files = readOwnedPerlCallbackVariantTar(bytes, "dependencies"), records = new Map(), expected = [];
	for(const pkg of dependencies.packages)
	{
		const path = `${pkg.directory}/.cargo-checksum.json`, original = files.get(path);
		assert.ok(original); assert.equal(sha256(original), pkg.manifestSha256);
		const manifest = JSON.parse(original); assert.equal(manifest.package, pkg.checksum);
		assert.equal(Object.keys(manifest.files).length, pkg.files); expected.push(path);
		for(const [relative, hash] of Object.entries(manifest.files))
		{
			const member = `${pkg.directory}/${relative}`; expected.push(member);
			assert.ok(files.has(member)); assert.equal(sha256(files.get(member)), hash, member);
		}
		records.set(`dependency-manifests/${pkg.directory}.json`, Buffer.from(original));
	}
	assert.deepEqual([...files.keys()].sort(), expected.sort());
	return records;
};
